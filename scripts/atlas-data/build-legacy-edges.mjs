#!/usr/bin/env node
/*
 * build-legacy-edges.mjs — Emit the slice of an older atlas graph that the
 * share-code decoder needs to recognise an intact older tree.
 *
 * Usage:
 *   git show f109065~1:src/data/atlas/atlasTreeData.json > /tmp/atlas-3.29.json
 *   node scripts/atlas-data/build-legacy-edges.mjs /tmp/atlas-3.29.json 29 \
 *     src/data/atlas/atlasTreeData.json > src/data/atlas/atlasTreeLegacyEdges.js
 *
 * Output: the older graph's edges between allocatable nodes whose skill id
 * still exists in the current tree, plus which of those touch the start
 * (root, or a bridge connected to root). That is all that is needed to test
 * "is this set of surviving ids a connected tree on the older graph".
 */

import fs from 'node:fs';

const [olderPath, generation, currentPath] = process.argv.slice(2);
if (!olderPath || !generation || !currentPath) {
  console.error('usage: build-legacy-edges.mjs <older data.json> <generation> <current data.json>');
  process.exit(1);
}

const older = JSON.parse(fs.readFileSync(olderPath, 'utf8')).nodes;
const current = JSON.parse(fs.readFileSync(currentPath, 'utf8')).nodes;
const currentSkills = new Set(Object.values(current).map(n => n.skill).filter(Boolean));

// Mirrors isAllocatable / getBridgeNodes in src/calculators/atlasTree.js
const isAllocatable = (id, n) => id !== 'root' && !n.isMastery && !!n.name;
const adj = {};
const link = (a, b) => {
  (adj[a] ??= new Set()).add(b);
  (adj[b] ??= new Set()).add(a);
};
for (const [id, n] of Object.entries(older)) {
  for (const o of n.out || []) link(id, o);
  for (const i of n.in || []) link(id, i);
}
const bridges = new Set(
  Object.entries(older)
    .filter(([id, n]) => id !== 'root' && !isAllocatable(id, n) && !n.isMastery && adj[id]?.size)
    .map(([id]) => id),
);
const skeleton = new Set(['root']);
const queue = ['root'];
while (queue.length) {
  for (const next of adj[queue.shift()] || []) {
    if (bridges.has(next) && !skeleton.has(next)) {
      skeleton.add(next);
      queue.push(next);
    }
  }
}

const shared = id => older[id] && isAllocatable(id, older[id]) && currentSkills.has(older[id].skill);
const start = new Set();
for (const s of skeleton) for (const n of adj[s] || []) if (shared(n)) start.add(older[n].skill);
const edges = [];
for (const [id, ns] of Object.entries(adj)) {
  if (!shared(id)) continue;
  for (const n of ns) {
    if (shared(n) && older[id].skill < older[n].skill) edges.push([older[id].skill, older[n].skill]);
  }
}
edges.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const gen = Number(generation);
process.stdout.write(`/*
 * atlasTreeLegacyEdges.js — GENERATED by scripts/atlas-data/build-legacy-edges.mjs.
 *
 * Older atlas graphs, reduced to the edges between allocatable nodes whose
 * skill id still exists in the bundled tree. Used by atlasTree.js
 * classifyUnmarkedAllocation to recognise an intact older tree.
 *
 * Generation ${gen}: grindinggear/atlastree-export graph bundled before
 * commit f109065 (the 3.30.0 import), i.e. f109065~1:src/data/atlas/atlasTreeData.json.
 */

export const LEGACY_GRAPHS = [
  {
    generation: ${gen},
    start: ${JSON.stringify([...start].sort((a, b) => a - b))},
    edges: ${JSON.stringify(edges)},
  },
];
`);
